// Known headshot face URLs or non-matching flatlays that should be replaced with real clothing photos
const DISALLOWED_INVALID_IMAGES = [
  'photo-1521572267360-ee0c2909d518', // Bearded man face portrait
  'photo-1508214751196-bcfd4ca60f91', // Woman face headshot
  'photo-1556905055-8f358a7a47b2'     // Orange beanie + grey knit sweater flatlay (mislabeled as hoodie)
];

export const isDisallowedHeadshot = (url) => {
  if (!url || typeof url !== 'string') return false;
  return DISALLOWED_INVALID_IMAGES.some((pattern) => url.includes(pattern));
};

/**
 * Detects the garment category (hoodie, tshirt, pants, jacket, dress)
 */
export const getGarmentType = (product) => {
  if (!product) return 'tshirt';
  const text = `${product.title || ''} ${product.subCategory || ''} ${product.description || ''}`.toLowerCase();
  if (text.includes('hoodie') || text.includes('sweatshirt') || text.includes('fleece')) return 'hoodie';
  if (text.includes('pant') || text.includes('cargo') || text.includes('jogger')) return 'pants';
  if (text.includes('jacket') || text.includes('coat') || text.includes('outerwear') || text.includes('bomber') || text.includes('puffer')) return 'jacket';
  if (text.includes('dress') || text.includes('skirt') || text.includes('gown')) return 'dress';
  return 'tshirt';
};

/**
 * Normalizes a color name to general brand category: 'Black', 'White', 'Pink', 'Purple'
 */
export const normalizeColorGroup = (colorName) => {
  if (!colorName || typeof colorName !== 'string') return 'Black';
  const c = colorName.toLowerCase();
  if (c.includes('pink') || c.includes('blush') || c.includes('rose') || c.includes('magenta') || c.includes('coral')) {
    return 'Pink';
  }
  if (c.includes('purple') || c.includes('violet') || c.includes('plum') || c.includes('lilac') || c.includes('lavender')) {
    return 'Purple';
  }
  if (c.includes('white') || c.includes('cream') || c.includes('ecru') || c.includes('chalk') || c.includes('ivory')) {
    return 'White';
  }
  return 'Black';
};

/**
 * Accurately returns an authentic apparel photograph matching the requested color AND garment type
 */
export const getColorMatchedImage = (product, selectedColor) => {
  if (!product) return 'https://images.unsplash.com/photo-1509967419530-da38b4704bc6?auto=format&fit=crop&w=900&q=80';

  const category = product.category === 'Women' ? 'Women' : product.category === 'Kids' ? 'Kids' : 'Men';
  const colorGroup = normalizeColorGroup(selectedColor);
  const garmentType = getGarmentType(product);

  // 1. Direct check in product.colorImages
  if (product.colorImages && typeof product.colorImages === 'object') {
    // Exact key match
    if (product.colorImages[selectedColor] && !isDisallowedHeadshot(product.colorImages[selectedColor])) {
      return product.colorImages[selectedColor];
    }
    // Case-insensitive key match
    for (const [key, imgUrl] of Object.entries(product.colorImages)) {
      if (key.toLowerCase() === (selectedColor || '').toLowerCase() && !isDisallowedHeadshot(imgUrl)) {
        return imgUrl;
      }
    }
    // Tone match inside colorImages
    for (const [key, imgUrl] of Object.entries(product.colorImages)) {
      if (normalizeColorGroup(key) === colorGroup && !isDisallowedHeadshot(imgUrl)) {
        return imgUrl;
      }
    }
  }

  // 2. Garment & Color Group Library lookup (e.g. hoodie + Black => Black Hoodie)
  if (GARMENT_COLOR_LIBRARY[garmentType]?.[colorGroup]) {
    return GARMENT_COLOR_LIBRARY[garmentType][colorGroup];
  }

  // 3. Category & color group fallback
  const pool = COLOR_APPAREL_LIBRARY[category]?.[colorGroup] || COLOR_APPAREL_LIBRARY.Men.Black;
  return pool[0];
};

/**
 * Returns a list of clean apparel images for a product, stripping headshot portraits or bad flatlays
 */
export const getCleanProductImages = (product, activeColor) => {
  if (!product) return [];
  const colorImg = getColorMatchedImage(product, activeColor);
  const rawList = Array.isArray(product.images) && product.images.length > 0 ? product.images : [colorImg];

  const cleaned = rawList
    .map((img) => (isDisallowedHeadshot(img) ? colorImg : img))
    .filter(Boolean);

  // Ensure current color image is at index 0
  if (cleaned.length === 0 || !cleaned.includes(colorImg)) {
    return [colorImg, ...cleaned].slice(0, 4);
  }
  return [colorImg, ...cleaned.filter((img) => img !== colorImg)].slice(0, 4);
};
