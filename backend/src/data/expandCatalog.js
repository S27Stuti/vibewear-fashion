// Helper to update files
function updateCatalogFiles() {
  const backendFilePath = path.join(__dirname, 'productsData.js');
  const frontendFilePath = path.join(__dirname, '../../../frontend/src/data/fallbackProducts.js');

  // Load existing backend sampleProducts
  let backendContent = fs.readFileSync(backendFilePath, 'utf8');
  let frontendContent = fs.readFileSync(frontendFilePath, 'utf8');

  // Insert additionalProducts before the closing ]; of sampleProducts / FALLBACK_PRODUCTS
  const addJson = additionalProducts.map(p => JSON.stringify(p, null, 2)).join(',\n  ');

  // For backend productsData.js
  const backendLastIndex = backendContent.lastIndexOf('];');
  if (backendLastIndex !== -1) {
    const updatedBackend = backendContent.slice(0, backendLastIndex) + ',\n  ' + addJson + '\n];' + backendContent.slice(backendLastIndex + 2);
    fs.writeFileSync(backendFilePath, updatedBackend, 'utf8');
    console.log('✅ Updated backend productsData.js with 36 new items!');
  }

  // For frontend fallbackProducts.js
  const frontendLastIndex = frontendContent.lastIndexOf('];');
  if (frontendLastIndex !== -1) {
    const updatedFrontend = frontendContent.slice(0, frontendLastIndex) + ',\n  ' + addJson + '\n];' + frontendContent.slice(frontendLastIndex + 2);
    fs.writeFileSync(frontendFilePath, updatedFrontend, 'utf8');
    console.log('✅ Updated frontend fallbackProducts.js with 36 new items!');
  }
}

updateCatalogFiles();
